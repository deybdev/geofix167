import { useEffect, useMemo, useState } from "react";
import { useNavigate } from "react-router-dom";
import { ChevronLeft, CircleCheck, MapPin } from "lucide-react";

import { Button } from "../../shared/components/ui/button";
import { PATHS } from "../../router/paths";
import InfraTimeline, {
  REPAIR_PHOTO_URL,
  STATUS_LINES,
  STAGES,
} from "./components/InfraTimeline";

/* Demo pacing: milliseconds to wait on each stage before advancing.
   The real workflow runs on the admin side; here it is simulated so the
   resident can see the whole infrastructure process end to end. */
const STAGE_DELAYS = [3000, 6000, 5000, 6000];

export default function InfraTracking({
  address,
  category,
  categoryLabel,
  photos = [],
}) {
  const navigate = useNavigate();

  // Unique report ID generated by "the system" on receive (stable per submit)
  const reportId = useMemo(
    () => `GF-167-${Math.random().toString(36).slice(2, 8).toUpperCase()}`,
    [],
  );

  // Demo simulation: the workflow advances one stage at a time
  const [stage, setStage] = useState(0);
  const [stageTimes, setStageTimes] = useState(() => [new Date().toISOString()]);

  useEffect(() => {
    if (stage >= STAGES.length - 1) return undefined;
    const timer = setTimeout(() => {
      setStage((s) => Math.min(s + 1, STAGES.length - 1));
      setStageTimes((ts) => [...ts, new Date().toISOString()]);
    }, STAGE_DELAYS[stage]);
    return () => clearTimeout(timer);
  }, [stage]);

  // Success splash first, then straight into the workflow timeline
  const [phase, setPhase] = useState("success");
  useEffect(() => {
    const timer = setTimeout(() => setPhase("timeline"), 2600);
    return () => clearTimeout(timer);
  }, []);

  const status = STATUS_LINES[stage];
  const resolved = stage >= STAGES.length - 1;

  // Photo evidence per stage: the resident's attachments on the submit
  // step, and the crew's before-and-after shots once repairs start
  const stagePhotos = useMemo(
    () => ({
      Submitted: photos.length ? photos : null,
      "In Progress": stage >= 3 ? [REPAIR_PHOTO_URL] : null,
    }),
    [photos, stage],
  );

  if (phase === "success") {
    return (
      <div className="mx-auto flex max-w-md flex-col items-center px-4 py-16 text-center">
        <span className="flex size-16 items-center justify-center rounded-full bg-primary/10">
          <CircleCheck size={40} className="text-primary" />
        </span>
        <h1 className="mt-4 text-xl font-bold text-slate-900">
          Report Submitted
        </h1>
        <p className="mt-1 text-sm leading-5 text-slate-500">
          Your infrastructure report was submitted successfully. Barangay
          staff will review it and send the right maintenance team.
        </p>
        <p className="mt-3 font-mono text-xs font-semibold uppercase tracking-wide text-slate-400">
          Report #{reportId}
        </p>
        <p className="mt-6 text-[11px] font-semibold text-emerald-600">
          Taking you to the workflow timeline…
        </p>
        <Button
          type="button"
          variant="outline"
          onClick={() => setPhase("timeline")}
          className="mt-4 h-10 rounded-lg px-5 text-xs font-semibold"
        >
          View workflow now
        </Button>
      </div>
    );
  }

  return (
    <section className="mx-auto max-w-md px-4 py-5 text-sm text-slate-700">
      {/* Header */}
      <div className="flex items-center gap-3">
        <button
          type="button"
          onClick={() => navigate(PATHS.resident)}
          aria-label="Back to home"
          className="flex size-9 shrink-0 items-center justify-center rounded-full border border-slate-200 text-slate-600 transition hover:border-primary hover:text-primary"
        >
          <ChevronLeft size={18} />
        </button>
        <h1 className="text-lg font-bold text-slate-900">
          Infrastructure Workflow
        </h1>
      </div>

      {/* Live status card */}
      <div className="mt-4 rounded-2xl border border-slate-200 p-4">
        <div className="flex items-center gap-2">
          {resolved ? (
            <span className="flex size-6 items-center justify-center rounded-full bg-emerald-100">
              <MapPin size={13} className="text-emerald-600" />
            </span>
          ) : (
            <span className="relative flex size-2.5">
              <span className="absolute inline-flex h-full w-full animate-ping rounded-full bg-primary opacity-75" />
              <span className="relative inline-flex size-2.5 rounded-full bg-primary" />
            </span>
          )}
          <p className={`text-sm font-bold ${status.color}`}>{status.text}</p>
        </div>
        <p className="mt-1.5 text-xs leading-4 text-slate-500">
          {categoryLabel || "Infrastructure"} • {address || "Pinned location"}
        </p>
        <p className="mt-0.5 font-mono text-[10px] font-semibold uppercase tracking-wide text-slate-400">
          Report #{reportId}
        </p>
      </div>

      {/* Workflow timeline */}
      <p className="mb-3 mt-6 text-xs font-bold uppercase tracking-wide text-slate-400">
        Workflow progress
      </p>
      <InfraTimeline
        category={category}
        categoryLabel={categoryLabel}
        reportId={reportId}
        currentStage={stage}
        stageTimes={stageTimes}
        photos={stagePhotos}
        createdAt={stageTimes[0]}
      />

      <Button
        type="button"
        onClick={() => navigate(PATHS.resident)}
        variant={resolved ? "default" : "outline"}
        className="mt-2 h-11 w-full rounded-xl text-sm font-semibold"
      >
        {resolved ? "Done" : "Back to Home"}
      </Button>
    </section>
  );
}
